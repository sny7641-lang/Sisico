#!/usr/bin/env python3
"""Build www/dictionary.js: an offline English-Korean dictionary for the search tab.

Sources
  data/dictionary/wiktionary_en_ko.jsonl : English Wiktionary entries that have Korean translations,
      extracted from kaikki.org (wiktextract) data. CC BY-SA 4.0 / GFDL.
      Regenerate: curl https://kaikki.org/dictionary/English/kaikki.org-dictionary-English.jsonl.gz
      | gunzip | python3 tools/filter_wiktionary.py data/dictionary/wiktionary_en_ko.jsonl
  data/dictionary/kowiktionary_en.jsonl : English entries of the Korean Wiktionary (definitions written in
      Korean), from https://kaikki.org/kowiktionary/ . CC BY-SA 4.0 / GFDL. Preferred source for meanings.
  data/dictionary/kengdic.tsv : Kengdic Korean-English dictionary (Joe Speigle), MPL 2.0 or LGPL 2.0+.
      https://github.com/garfieldnate/kengdic . Used in reverse (English gloss -> Korean word).
"""
import json, os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DD = os.path.join(ROOT, 'data', 'dictionary')
POS = {'noun': 'n.', 'verb': 'v.', 'adj': 'adj.', 'adv': 'adv.', 'name': '고유명사', 'phrase': 'phr.', 'intj': 'interj.',
       'num': 'num.', 'prep': 'prep.', 'conj': 'conj.', 'pron': 'pron.', 'det': 'det.', 'proverb': '속담', 'prep_phrase': 'phr.',
       'article': 'art.', 'particle': 'part.', 'prefix': 'prefix', 'suffix': 'suffix', 'abbrev': '약어', 'symbol': '기호'}

entries = collections.OrderedDict()   # key -> {w, pos:[], ipa, wk:[], kd:[], g}

def add(key, word):
    e = entries.get(key)
    if not e:
        e = entries[key] = {'w': word, 'pos': [], 'ipa': '', 'wk': [], 'kd': [], 'g': '', 'kw': []}
    return e

for line in open(os.path.join(DD, 'wiktionary_en_ko.jsonl'), encoding='utf-8'):
    x = json.loads(line)
    w = (x.get('w') or '').strip()
    if not w:
        continue
    e = add(w.lower(), w)
    p = POS.get(x.get('p'), x.get('p') or '')
    if p and p not in e['pos']:
        e['pos'].append(p)
    if not e['ipa'] and x.get('ipa'):
        e['ipa'] = x['ipa']
    if not e['g']:
        e['g'] = next((g for g in x.get('g') or [] if g), '')
    for ko, sense, roman in x['tr']:
        ko = ko.strip()
        if ko and ko not in e['wk'] and len(e['wk']) < 8:
            e['wk'].append(ko)

HANGUL = re.compile(r'[가-힣]')
for line in open(os.path.join(DD, 'kowiktionary_en.jsonl'), encoding='utf-8'):
    x = json.loads(line)
    w = (x.get('word') or '').strip()
    if not w:
        continue
    senses = []
    for sn in x.get('senses') or []:
        g = (sn.get('glosses') or [''])[0]
        g = re.sub('[\u3200-\u32ff]', '', g).strip().rstrip('.').strip()
        if g and HANGUL.search(g) and len(g) <= 60:
            senses.append(g)
    if not senses:
        continue
    e = add(w.lower(), w)
    p = POS.get(x.get('pos'), '')
    if p and p not in e['pos']:
        e['pos'].append(p)
    if not e['ipa']:
        e['ipa'] = next((sd['ipa'] for sd in x.get('sounds') or [] if sd.get('ipa')), '')
    for g in senses:
        if g not in e['kw'] and len(e['kw']) < 6:
            e['kw'].append(g)

for line in open(os.path.join(DD, 'kengdic.tsv'), encoding='utf-8'):
    p = line.rstrip('\n').split('\t')
    if len(p) < 4 or p[0] == 'id':
        continue
    ko, gloss = p[1].strip(), p[3].strip()
    if not ko or not gloss or not HANGUL.search(ko):
        continue
    for g in re.split(r'[;,]', gloss):
        g = re.sub(r'\(.*?\)', '', g).strip().lower()
        g = re.sub(r'^(to|a|an|the) ', '', g)
        if not g or len(g) > 40 or not re.match(r"^[a-z][a-z' .\-]*$", g):
            continue
        e = add(g, g)
        if ko not in e['kd'] and ko not in e['wk'] and len(e['kd']) < 6:
            e['kd'].append(ko)

rows = []
for k, e in entries.items():
    if not e['wk'] and not e['kd'] and not e['kw']:
        continue
    rows.append([e['w'], ' / '.join(e['pos']), e['ipa'], '; '.join(e['wk']), '; '.join(e['kd']), e['g'][:120], '; '.join(e['kw'])])
rows.sort(key=lambda r: r[0].lower())
js = ('// Generated by tools/build_dictionary.py. Sources: English Wiktionary via kaikki.org (CC BY-SA 4.0),\n'
      '// Kengdic (MPL 2.0 / LGPL 2.0+). Row: [word, part of speech, IPA, en.Wiktionary Korean, Kengdic Korean, English gloss, ko.Wiktionary Korean]\n'
      'window.SISICO_DICTIONARY = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(os.path.join(ROOT, 'www', 'dictionary.js'), 'w', encoding='utf-8').write(js)
print('entries', len(rows), 'kowikt', sum(1 for r in rows if r[6]), 'wiktionary', sum(1 for r in rows if r[3]), 'kengdic-only', sum(1 for r in rows if not r[3] and not r[6]),
      'size', len(js.encode()) // 1024, 'KB')
